def export_for_manual_testing(templates, filename):
    """Export prompts to a file for copy-paste testing."""
    with open(filename, 'w') as f:
        for i, t in enumerate(templates):
            f.write(f"=== PROMPT {i+1} ===\n")
            f.write(f"Analyzing: Step {t['output_node'].step_idx} → Step {t['step_idx']}\n\n")
            f.write(t['prompt'])
            f.write("\n\n--- YOUR RESPONSE ---\n\n\n")


