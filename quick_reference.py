# 7. COMPLETE WORKFLOW
# ============================================================

def analyze_trajectory(steps, problem, ground_truth, llm_fn=None):
    """Complete workflow for analyzing a failed trajectory."""
    
    # Build graph
    graph = trajectory_to_graph(steps, problem, ground_truth)
    
    # Compute loss
    loss = compute_loss(graph.get_loss(), ground_truth, problem)
    
    if llm_fn is None:
        # Export for manual testing
        templates = graph.linearize(loss)
        export_for_manual_testing(templates, "prompts_output.txt")
        print(f"Exported {len(templates)} prompts to prompts_output.txt")
        return templates
    else:
        # Run automated analysis
        executor = BackwardExecutor(llm_fn)
        results = executor.run(graph, loss)
        suspects = executor.get_top_suspects(graph, k=3)
        
        print("Analysis complete. Top suspects:")
        for s in suspects:
            print(f"  Step {s['step_idx']} ({s['role']}): {s['score']:.2f}")
        
        return results, suspects
